#multiplying/repeating a strings with asterisk operator (*)- A string manipulation operator
'''
- It multiplies a string as many times as required. 
-SYNTAX:-
 var_name = "string-1" * no._of_times
'''
#Example-1
a = "Eisha "
b = a*3
print(b)

'''
Output: -

Eisha Eisha Eisha 
'''

#Example-2
l = "Happy "
q = l*4
print(q)

'''
Output: -

Happy Happy Happy Happy 
'''