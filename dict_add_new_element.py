'''
Adding new element in an Existing dictionary:-
SYNTAX: dictionary_name[key] = value/"value"
'''

#Example:-
students = {1:"Abhi", 2:"Cutie", 3: "Divyanka", 4: "Esha"}
print(students)
#Output: {1: 'Abhi', 2: 'Cutie', 3: 'Divyanka', 4: 'Esha'}

#Adding 5:"Harry" to the above dictioanry:-
students[5]="Harry"
print(students)
#Output: {1: 'Abhi', 2: 'Cutie', 3: 'Divyanka', 4: 'Esha', 5: 'Harry'}