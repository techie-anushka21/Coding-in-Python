#exponents

#integers
num1 = 10 
num2 = 2
expo1 = num1**num2
print(expo1)    #Output: 100

#floating point numbers
num3 = 5.1
num4 = 2.2
expo2 = num3**num4
print(expo2)    #Output: 36.029180782470974

#complex numbers
num5 = 2+2j
num6 = 1-2j
expo3 = num5**num6
print(expo3)    #Output: (3.7176395160348648-13.088342045157981j)