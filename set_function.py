#Empty set:-
empty_set = set()
print(empty_set)    #Output: set()
print(type(empty_set))    #Output: <class 'set'>

#Another example:-
set3 = set("HAPPY")
print(set3)         #Output: {'Y', 'A', 'P', 'H'}

#Example-3:-
set4 = set({"Pink","Orange","Green","Golden"})
print(set4)         #Output: {'Pink', 'Orange', 'Golden', 'Green'}
print(len(set4))    #Output: 4 (means there are 4 elements in the set)
print(type(set4))   #Output: <class 'set'>

#Example-4: -
set5 = set(["HAPPY"])
print(set5)          #Output: {'HAPPY'}
print(type(set5))    #Output: <class 'set'>