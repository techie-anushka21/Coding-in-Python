'''
List:-
-List is a Sequence data type in Python.
-It behaves like a Dynamic Array.
-It can be empty. Empty list can be created by list() or list_name = []
-It is mutable.
'''

#Creating our 1st List in Python:-
my_list = [1,'A','Student',98.6]
print(my_list)    #Output: [1, 'A', 'Student', 98.6]

#Another list:-
students = ['Abhi','Surbhi','Heera','Anna']
print(students)   #Output: ['Abhi', 'Surbhi', 'Heera', 'Anna']

'''In a List of Strings, the names will sort in alphabetical order when we use the sort function.'''

#Empty list
empty_list = []
print(empty_list)    #Output: []