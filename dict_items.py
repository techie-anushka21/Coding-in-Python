#Example 1:-
students = {1: "Abhi", 2: 'Dipti', 3: 'Divyanka', 4: 'Esha', 5: 'Harry'}
for key,value in students.items():
    print(key,value)

'''Output:  1 Abhi
            2 Dipti
            3 Divyanka
            4 Esha
            5 Harry
'''

#Example 2:-
emp = {101:'Abhi', 102:'Dipti', 103:'Divyanka', 104: 'Esha', 105: 'Harry'}
for key,value in emp.items():
    print(key,"=",value)

'''
Output: 101 = Abhi
        102 = Dipti
        103 = Divyanka
        104 = Esha
        105 = Harry
'''