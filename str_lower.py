'''
String functions- lower() : it converts the string to lowercase.
- SYNTAX: -
  var_name = literal/variable.lower()
'''

#Example 1: -
print("CUTE".lower())          #1st way

# Output: -
# cute

a = "CUTE"
res = a.lower()                #2nd way
print(res)

# Output: -
# cute

#Example 2: -
print("Adorable".lower())      #1st way

# Output: -
# adorable

b = "Adorable"                 #2nd way
res2 = b.lower()
print(res2)

# Output: -
# adorable