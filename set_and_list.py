#Example-1:-
set_and_list = set([10,10,20,30,40,50])
print(set_and_list)    #Output: {40, 10, 50, 20, 30}
print(type(set_and_list))    #<class 'set'>


#Example-2:-
set_and_list2 = set(["pink","green","yellow","golden"])
print(set_and_list2)   #Output: {'golden', 'yellow', 'pink', 'green'}
print(type(set_and_list2))    #<class 'set'>

