#for...in...range LOOP statement- Minimum 1 maximum 3 arguments can be passed.

#Example 1:-
for a in range(5):
    print(a)

'''
Output: -

0
1
2
3
4
'''

#Example 2:-
for i in range(0,5):
    print(i)

'''
Output: -

0
1
2
3
4
'''

