#swapping of 2 numbers (12 and 7)
num1 = 12
num2 = 7
print("Before swapping:-")
print("num1 = ",num1)
print("num2 = ",num2)
temp = num1    #swapping starts
num1 = num2  
num2 = temp    #swapping ends
print("After swapping:-")
print("num1 = ",num1)
print("num2 = ",num2)

