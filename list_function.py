'''
 Using list() function in Python
-It is another way of creating lists in Python.
'''

#Empty list:-
empty_list2 = list()
print(empty_list2)          # Output: []
print(type(empty_list2))    # Output: <class 'list'>

#Non-empty list:-
emp2 = list([102,'Harshie',44.8,'HoD-IT'])
print(emp2)                 #Output: [102, 'Harshie', 44.8, 'HoD-IT']
print(type(emp2))    # Output: <class 'list'>