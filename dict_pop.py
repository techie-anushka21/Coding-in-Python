#Example:-
students = {1:"Abhi", 2:"Vidhi", 3:"Khyati", 4:"Vineet"}
print(students)    #Output: {1:"Abhi", 2:"Vidhi", 3:"Khyati", 4:"Vineet"}

#To pop key 3 and return its value:-
value = students.pop(3)
print(value)       #Output: Khyati

print(students)    #Output: {1:"Abhi", 2:"Vidhi", 4:"Vineet"}