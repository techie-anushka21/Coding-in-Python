#dividing 10 by 3 to get remainder, half and full quotient.
num1 = 10    #dividend 
num2 = 3    #divisor
rem = num1%num2  #remainder
hqt = num1//num2 #half quotient
fqt = num1/num2  #full quotient
print("1st no.: ",num1)
print("2nd no.: ",num2)
print("Remainder = ", rem)
print("Half quotient = ", hqt)
print("Full quotient = ", fqt)