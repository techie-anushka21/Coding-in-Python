'''
Logical operators in Python: -

- They combine/modify Conditional Statements and return boolean result (True or False).
- They are of 3 types: -

  1. logical 'and' operator- returns True when all conditions are True, else False.

  2. logical 'or' operator- returns True if at least 1 of the conditions is true or both are true. 
     Returns False only if all conditions are False.
    
  3. logical 'not' operator- True->False, False->True
'''