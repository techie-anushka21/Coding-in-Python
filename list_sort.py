list1 = [15,31,1,9]    #list creation
print(list1)           #Output: [15, 31, 1, 9]

list1.sort()           #command to sort the list1 elements in ASCENDING order
print(list1)           #Output: [1, 9, 15, 31]

list1.sort(reverse=True)    #command to sort the list1 elements in DESCENDING order
print(list1)                #Output: [31, 15, 9, 1]