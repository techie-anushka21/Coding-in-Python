'''
String functions- upper() : it converts the string to uppercase.
- SYNTAX: -
  var_name = literal/variable.upper()
'''

#Example 1
print("cute".upper())     #1st way

# Output: -
# CUTE

a = "cute"
res = a.upper()           #2nd way
print(res)

# Output: -
# CUTE


#Example 2
print("Delhi".upper())    #1st way

# Output: -
# DELHI

b = "Delhi"
res2 = b.upper()          #2nd way
print(res2)

# Output: -
# DELHI